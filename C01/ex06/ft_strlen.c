#include <stdio.h>

int	ft_strlen(char *str)
{
	int	i;

	i = 0;
	while (str[i])
	{
		i++;
	}
	return (i);
}

int main()
{
    char *src = "Bonj\0";

    printf("chaine -> %d", ft_strlen(src));
    return 0;
}